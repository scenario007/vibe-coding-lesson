test('plays real source separation tracks in the completed report', async ({ page }) => {
  test.skip(!song, 'Set VOCALLAB_REAL_API_FIXTURES to the real sample directory.')
  await page.goto('/')
  await page.getByLabel('原唱文件').setInputFiles(resolve(song!, 'mix.wav'))
  await page.getByLabel('我的演唱文件').setInputFiles(resolve(song!, 'clean.wav'))
  const mode = page.getByRole('region', { name: '原唱', exact: true }).getByLabel('分离模式')
  await expect(mode).toHaveValue('fast')
  await expect(mode.getByRole('option', { name: /BS-RoFormer/ })).toHaveCount(1)
  await page.getByRole('button', { name: '开始分析' }).click()
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toBeVisible({ timeout: 270_000 })
  const track = page.getByLabel('试听音轨')
  await expect(track).toHaveValue('vocals')
  await expect(page.getByText('音高分析使用 分离人声')).toBeVisible()
  const spectrum = page.getByRole('region', { name: '声谱图', exact: true })
  const spectrumPlot = spectrum.getByRole('img', { name: '当前音频声谱图' })
  await expect(spectrumPlot).toBeVisible()
  await spectrumPlot.hover({ position: { x: 100, y: 100 } })
  await expect(spectrum.getByText(/频点 .* Hz .* dBFS/)).toBeVisible()
  await spectrum.getByLabel('频率上限').selectOption('5000')
  await expect(spectrum.getByText('5000 Hz', { exact: true })).toBeVisible()
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate(el => el.readyState)).toBeGreaterThan(0)
  await track.selectOption('instrumental')
  await expect(audio).toHaveAttribute('src', /\/instrumental$/)
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停' })).toBeVisible()
  await track.selectOption('original')
  await expect(audio).toHaveAttribute('src', /\/original$/)
  await expect(spectrum.getByText(/A 原唱 · 原始音频/)).toBeVisible()
  await expect(spectrumPlot).toBeVisible()
})

test('manual anchors sync A/B even when a track has no usable pitch', async ({ page }) => {
  const silent = resolve(fixtures, 'silent.wav')
  execFileSync('ffmpeg', ['-nostdin', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=22050:cl=mono',
    '-t', '6', silent])
  await page.goto('/')
  await page.getByLabel('原唱文件').setInputFiles(resolve(fixtures, 'reference.mp3'))
  await page.getByLabel('我的演唱文件').setInputFiles(silent)
  await page.getByRole('region', { name: '原唱', exact: true }).getByRole('checkbox', { name: /含伴奏/ }).uncheck()
  await page.getByRole('button', { name: '开始分析' }).click()
  const audio = page.locator('audio')
  const independentCharts = page.getByRole('img', { name: '独立音高曲线' })
  await expect(independentCharts).toHaveCount(2, { timeout: 125_000 })
  await page.getByRole('button', { name: 'B 我的演唱' }).click()
  await independentCharts.nth(1).click({ position: { x: 280, y: 100 } })
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeGreaterThan(.8)
  const anchor = await audio.evaluate(el => el.currentTime)
  await page.getByRole('button', { name: '用两轨当前位置对齐' }).click()
  await expect(page.getByText(/按手动对齐点显示对应位置/)).toBeVisible({ timeout: 125_000 })
  await expect(page.getByLabel('音准命中率')).toHaveText('—')
  await page.getByRole('button', { name: 'B 我的演唱' }).click()
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeCloseTo(anchor, 1)
})
