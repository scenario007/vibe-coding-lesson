  await expect(page.getByRole('button', { name: '曲线重置' })).toBeEnabled()
  await page.getByRole('button', { name: '曲线重置' }).click()
  await expect(page.getByRole('heading', { name: 'A/B 对照复听' })).toHaveCount(0)
