test('keeps independent plots without alignment and honors a manual offset during playback', async ({ page }) => {
  const silent = resolve(fixtures, 'silent.wav')
  execFileSync('ffmpeg', ['-nostdin', '-y', '-v', 'error', '-f', 'lavfi', '-i', 'anullsrc=r=22050:cl=mono',
    '-t', '6', silent])
  await page.goto('/')
  await page.getByLabel('原唱文件').setInputFiles(resolve(fixtures, 'reference.mp3'))
  await page.getByLabel('我的演唱文件').setInputFiles(silent)
  await page.getByRole('region', { name: '原唱', exact: true }).getByRole('checkbox', { name: /含伴奏/ }).uncheck()
  await page.getByRole('button', { name: '开始分析' }).click()
  const a = page.getByTestId('pitch-audio-reference')
  const b = page.getByTestId('pitch-audio-user')
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toBeVisible({ timeout: 125_000 })
  await expect(page.getByRole('img', { name: '独立音高曲线' })).toHaveCount(2)
  await seek(page, .8)
  await expect.poll(() => b.evaluate(el => el.currentTime)).toBeCloseTo(.8, 2)
  await page.getByLabel('手动偏移（秒）').fill('1.15')
  await page.getByRole('button', { name: '应用偏移' }).click()
  await expect(page.getByText(/当前手动偏移 \+1.15 秒/)).toBeVisible()
  await expect(page.getByText(/可评 0 · 翻唱静音 [1-9]/)).toBeVisible()
  await seek(page, 1.2)
  await expect.poll(() => a.evaluate(el => el.currentTime)).toBeCloseTo(1.2, 2)
  await expect.poll(() => b.evaluate(el => el.currentTime)).toBeCloseTo(2.35, 2)
})
