  await page.getByRole('button', { name: '开始分析' }).click()
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toBeVisible({ timeout: 125_000 })
  await expect(page.getByLabel('音准分结果', { exact: true })).toHaveText(/\d+(\.\d+)?\s*\/ 100/)
  await expect(page.getByRole('list', { name: '逐段音准' })).toBeVisible()
  const noteDetails = page.getByText('音符明细', { exact: true }).first()
  await noteDetails.click()
