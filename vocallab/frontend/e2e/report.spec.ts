test('loads actual MP3 and HEVC MOV, renders aligned data and seeks to matching audio', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '对比原唱与我的演唱' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('upload.png'), fullPage: true })
  const reference = page.getByRole('region', { name: '原唱' })
  const user = page.getByRole('region', { name: '我的演唱' })
  await reference.getByLabel('原唱文件').setInputFiles(resolve(fixtures, 'reference.mp3'))
  await user.getByLabel('我的演唱文件').setInputFiles(resolve(fixtures, 'delayed.mov'))
  await expect(reference.getByText('reference.mp3')).toBeVisible()
  await expect(user.getByText('delayed.mov')).toBeVisible()
  await reference.getByRole('checkbox', { name: /含伴奏/ }).uncheck()
  await reference.getByLabel('终点（秒）').fill('5.8')
  await user.getByLabel('终点（秒）').fill('6.8')
  await page.getByRole('button', { name: '开始分析' }).click()
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toBeVisible({ timeout: 125_000 })
  await expect(page.getByLabel('音准命中率')).toHaveText(/\d+\.\d+%/)
  const curveSource = page.getByLabel('曲线来源')
  await expect(curveSource).toHaveValue('harmonic')
  await expect(page.getByTestId('harmonic-curve-reference')).toHaveAttribute('d', /M.*L/)
  await curveSource.selectOption('review')
  await expect(page.getByTestId('harmonic-curve-reference')).toHaveCount(0)
  await curveSource.selectOption('harmonic')
  const chart = page.getByRole('img', { name: '原唱与我的演唱对齐音高曲线' })
  await expect(chart).toBeVisible()
  await expect(chart.locator('text').filter({ hasText: /^C3$/ })).toHaveCount(1)
  await page.getByRole('button', { name: '放大曲线' }).click()
  await expect(page.getByText('移动视图')).toBeVisible()
  await page.getByRole('button', { name: '曲线重置' }).click()
  await chart.click({ position: { x: 240, y: 110 } })
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeGreaterThan(.4)
  const referenceTime = await audio.evaluate(el => el.currentTime)
  await page.getByRole('button', { name: 'B 我的演唱' }).click()
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeGreaterThan(referenceTime + .65)
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeLessThan(referenceTime + 1.35)
  await page.getByRole('button', { name: '播放', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停' })).toBeVisible()
  await page.getByRole('button', { name: '暂停' }).click()
  await page.getByRole('button', { name: '循环区间' }).click()
  await expect(page.getByRole('button', { name: '循环区间' })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: info.outputPath('report.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: info.outputPath('report-mobile.png'), fullPage: true })
  const savedUrl = page.url()
  const wave = page.getByRole('img', { name: '翻唱波形包络' }).locator('path')
  const userCurve = page.getByTestId('harmonic-curve-user')
  const beforeWave = await wave.getAttribute('d')
  const beforeCurve = await userCurve.getAttribute('d')
  const beforeScore = await page.getByLabel('音准命中率').textContent()
  await page.getByLabel('手动偏移（秒）').fill('0.35')
  await page.getByRole('button', { name: '应用偏移' }).click()
  await expect(page.getByText(/当前手动偏移 \+0.35 秒/)).toBeVisible()
  await expect(wave).not.toHaveAttribute('d', beforeWave!)
  await expect(userCurve).not.toHaveAttribute('d', beforeCurve!)
  await expect(page.getByLabel('音准命中率')).not.toHaveText(beforeScore!)
  expect(page.url()).toBe(savedUrl)
  await page.getByRole('button', { name: 'A 原唱' }).click()
  await chart.click({ position: { x: 150, y: 100 } })
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeGreaterThan(.4)
  const adjustedReferenceTime = await audio.evaluate(el => el.currentTime)
  await page.getByRole('button', { name: 'B 我的演唱' }).click()
  await expect.poll(() => audio.evaluate(el => el.currentTime)).toBeCloseTo(adjustedReferenceTime + .35, 2)
  await page.reload()
  await expect(page.getByText(/当前手动偏移 \+0.35 秒/)).toBeVisible()
  await page.getByLabel('复听起点（秒）').fill('0.5')
  await page.getByLabel('复听起点（秒）').press('Enter')
  await page.getByLabel('复听终点（秒）').fill('4.5')
  await page.getByLabel('复听终点（秒）').press('Enter')
  await page.getByRole('button', { name: '用原唱选区检测' }).click()
  await expect(page.getByText(/自动检测到翻唱延迟.*原唱选区 0:00.50–0:04.50/)).toBeVisible()
  expect(errors).toEqual([])
})

test('shows a playable harmonic preview before formal analysis completes', async ({ page }, info) => {
  const longVoice = info.outputPath('long-voice.wav')
  execFileSync('ffmpeg', ['-nostdin', '-y', '-v', 'error', '-stream_loop', '5', '-i',
    resolve(fixtures, 'reference.wav'), '-t', '30', longVoice])
  await page.goto('/')
  await page.getByLabel('原唱文件').setInputFiles(longVoice)
  await page.getByLabel('我的演唱文件').setInputFiles(longVoice)
  await page.getByRole('region', { name: '原唱', exact: true }).getByRole('checkbox', { name: /含伴奏/ }).uncheck()
  await page.getByRole('button', { name: '开始分析' }).click()
  const preview = page.getByRole('region', { name: '快速基频预览' })
  const chart = preview.getByRole('img', { name: '独立音高曲线' }).first()
  const audio = preview.getByLabel('原唱预览音频')
  await expect(preview.getByTestId('harmonic-curve-reference')).toHaveAttribute('d', /M.*L/, { timeout: 125_000 })
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toHaveCount(0)
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.readyState)).toBeGreaterThan(0)
  await chart.click({ position: { x: 210, y: 100 } })
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.currentTime)).toBeGreaterThan(0)
  await expect(page.getByRole('heading', { name: '演唱分析报告' })).toBeVisible({ timeout: 125_000 })
})

