  const background = chart.getByTestId('pitch-background')
  const x = await playhead.getAttribute('x1')
  const backgroundX = async () => Number((await background.getAttribute('transform'))?.match(/translate\(([-.\d]+)/)?.[1])
  await expect(original).toBeChecked()
  await expect(cover).not.toBeChecked()
  const centerNotes = page.getByRole('region', { name: '音高曲线' }).getByTestId('pitch-playhead-notes')
  await seek(page, 1)
