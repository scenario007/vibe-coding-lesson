  await expect(page.getByText(/当前手动偏移 \+0.35 秒/)).toBeVisible()
  await expect(wave).not.toHaveAttribute('d', beforeWave!)
  await expect(userCurve).not.toHaveAttribute('d', beforeCurve!)
  await expect(page.getByLabel('音准分结果', { exact: true })).not.toHaveText(beforeScore!)
  expect(page.url()).toBe(savedUrl)
  await seek(page, 1.8)
  await expect.poll(() => referenceAudio.evaluate(el => el.currentTime)).toBeCloseTo(1.8, 2)
  await expect.poll(() => coverAudio.evaluate(el => el.currentTime)).toBeCloseTo(2.15, 2)
  await page.reload()
  await expect(page.getByText(/当前手动偏移 \+0.35 秒/)).toBeVisible()
  await page.getByText('原唱复听与检测选区', { exact: true }).click()
  await page.getByLabel('复听起点（秒）').fill('0.5')
  await page.getByLabel('复听起点（秒）').press('Enter')
  await page.getByLabel('复听终点（秒）').fill('4.5')
